import "dotenv/config";
import { PrismaClient } from "../app/generated/prisma/client.js";
// eslint-disable-next-line @typescript-eslint/no-require-imports
const { PrismaBetterSqlite3 } = require("@prisma/adapter-better-sqlite3");
import bcrypt from "bcryptjs";
import crypto from "crypto";
import fs from "fs";
import path from "path";
import { seedTaxonomy, seedScoreConversions } from "./seed-taxonomy.js";

// ─────────────────────────────────────────────────────────────────────────────
// Production seed for the "Sat Sol" platform.
//
// Unlike prisma/seed.ts (demo), this seeds ONLY what a real deployment needs:
//   • academic taxonomy (Section → Domain → Topic → Subskill + TaxonomyNode)
//   • SAT score-conversion tables (needed for Full Practice Test scoring)
//   • governance AppSettings (all defaulting OFF)
//   • ONE admin account
// No teachers, students, parents, programs, demo questions, Practice Sets,
// attempts, invites or mock exams. Academic content comes from AI Import.
//
// Admin password handling:
//   • Injectable — set PROD_ADMIN_PASSWORD to provide your own.
//   • Otherwise the seed generates a strong random one and writes it, in plain
//     text, to .secrets/prod-admin-credentials.txt (gitignored, never committed).
//   • Idempotent — on re-run an existing admin's password is left untouched
//     unless PROD_ADMIN_RESET=true (or PROD_ADMIN_PASSWORD is provided).
// ─────────────────────────────────────────────────────────────────────────────

const url = process.env.DATABASE_URL ?? "file:./prisma/prod.db";
const adapter = new PrismaBetterSqlite3({ url });
const prisma = new PrismaClient({ adapter });

const ADMIN_EMAIL = (process.env.PROD_ADMIN_EMAIL ?? "admin@satsol.org").trim().toLowerCase();
const ADMIN_NAME = process.env.PROD_ADMIN_NAME ?? "Sat Sol Admin";
const RESET = process.env.PROD_ADMIN_RESET === "true";

const SECRETS_DIR = path.resolve(process.cwd(), ".secrets");
const CREDENTIALS_FILE = path.join(SECRETS_DIR, "prod-admin-credentials.txt");

// URL-safe, ~32-char password. Strong enough for a bootstrap admin the operator
// is expected to change (or replace with SSO/invite) after first login.
function generatePassword(): string {
  return crypto.randomBytes(24).toString("base64url");
}

function writeCredentialsFile(email: string, password: string, injected: boolean): void {
  fs.mkdirSync(SECRETS_DIR, { recursive: true });
  const body = [
    "# Sat Sol — bootstrap admin credentials (PLAINTEXT, gitignored).",
    "# Generated by `npm run db:seed:prod`. Do NOT commit. Rotate after first login.",
    `# Generated at: ${new Date().toISOString()}`,
    `# Source: ${injected ? "PROD_ADMIN_PASSWORD (injected)" : "auto-generated"}`,
    "",
    `PROD_ADMIN_EMAIL=${email}`,
    `PROD_ADMIN_PASSWORD=${password}`,
    "",
  ].join("\n");
  fs.writeFileSync(CREDENTIALS_FILE, body, { mode: 0o600 });
}

async function main() {
  // ─── Taxonomy + score tables + governance settings ─────────────────────────
  await seedTaxonomy(prisma);
  await seedScoreConversions(prisma);

  await Promise.all(
    [
      "STUDENT_UNLOCK_REQUESTS",
      "STUDENT_SELF_ENROLLMENT",
      "TEACHER_PROGRAM_MANAGEMENT",
      "TEACHER_GROUP_MANAGEMENT",
    ].map((key) =>
      prisma.appSetting.upsert({
        where: { key },
        update: {}, // never override an operator's choice on re-seed
        create: { key, value: "false" },
      })
    )
  );

  // ─── Bootstrap admin ────────────────────────────────────────────────────────
  const existing = await prisma.user.findUnique({ where: { email: ADMIN_EMAIL } });
  const injected = Boolean(process.env.PROD_ADMIN_PASSWORD);
  const password = process.env.PROD_ADMIN_PASSWORD || generatePassword();

  if (!existing) {
    await prisma.user.create({
      data: {
        name: ADMIN_NAME,
        email: ADMIN_EMAIL,
        passwordHash: await bcrypt.hash(password, 10),
        role: "ADMIN",
        active: true,
        validationStatus: "APPROVED",
      },
    });
    writeCredentialsFile(ADMIN_EMAIL, password, injected);
    console.log(`\n✅  Admin creado: ${ADMIN_EMAIL}`);
    console.log(`    Contraseña escrita en: ${path.relative(process.cwd(), CREDENTIALS_FILE)} (gitignored)`);
  } else if (RESET || injected) {
    await prisma.user.update({
      where: { email: ADMIN_EMAIL },
      data: { passwordHash: await bcrypt.hash(password, 10), active: true, validationStatus: "APPROVED" },
    });
    writeCredentialsFile(ADMIN_EMAIL, password, injected);
    console.log(`\n✅  Admin actualizado (password reseteada): ${ADMIN_EMAIL}`);
    console.log(`    Nueva contraseña en: ${path.relative(process.cwd(), CREDENTIALS_FILE)} (gitignored)`);
  } else {
    console.log(`\nℹ️   Admin ya existe: ${ADMIN_EMAIL} — contraseña sin cambios.`);
    console.log("    Para resetearla: PROD_ADMIN_RESET=true npm run db:seed:prod");
  }

  console.log("\n✅  Seed de producción completo (taxonomía + tablas de score + settings + admin).");
  console.log("    Sin usuarios/preguntas demo. El contenido académico se crea vía AI Import.\n");
}

main()
  .catch((err) => {
    console.error(err);
    process.exitCode = 1;
  })
  .finally(() => prisma.$disconnect());
